'use strict';
const assert=require('node:assert/strict');
const {parseAmount,shares,balances,suggestions,validateGroup,validate}=require('../split-expenses.js');
const group={id:'group',name:'Hostel',members:['You','Aditi','Rahul'],entries:[]};
let id=0;
const add=e=>group.entries.push({id:String(++id),date:'2026-11-01',...e});
assert.equal(parseAmount('120.50'),12050);
assert.throws(()=>parseAmount('1.001'));
assert.throws(()=>parseAmount('-1'));
assert.deepEqual(shares(100,3),[34,33,33]);
assert.equal(shares(101,3).reduce((a,b)=>a+b),101);
add({type:'bill',title:'Groceries',payer:'You',amount:100});
assert.deepEqual(balances(group),{You:66,Aditi:-33,Rahul:-33});
assert.deepEqual(suggestions(group),[{from:'Aditi',to:'You',amount:33},{from:'Rahul',to:'You',amount:33}]);
add({type:'settlement',from:'Aditi',to:'You',amount:20});
validateGroup(group);
assert.deepEqual(balances(group),{You:46,Aditi:-13,Rahul:-33});
add({type:'bill',title:'Bus',payer:'Rahul',amount:300});
validateGroup(group);
const plan=suggestions(group);
assert.equal(Object.values(balances(group)).reduce((a,b)=>a+b),0);
for(const t of plan)add({type:'settlement',...t});
validateGroup(group);
assert.deepEqual(balances(group),{You:0,Aditi:0,Rahul:0});
assert.deepEqual(suggestions(group),[]);
const over=structuredClone(group);over.entries.push({id:'over',date:'2026-11-01',type:'settlement',from:'Aditi',to:'You',amount:1});
assert.throws(()=>validateGroup(over),/exceeds/);
assert.throws(()=>validateGroup({...group,members:['You','you']}));
assert.throws(()=>validate({version:1,groups:[group,group]}),/Duplicate/);
const bad=structuredClone(group);bad.entries[0].date='2026-02-30';assert.throws(()=>validateGroup(bad));
assert.equal(validate({version:1,groups:[group],selected:'missing'}).selected,'group');
console.log('PASS: exact paise, remainder allocation, debt conservation, multiple payers, partial settlements, full settlement, overpayment rejection, invalid backups and dates');
